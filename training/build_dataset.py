def kit_lines(n_per_tactic=16):
    sys.path.insert(0, str(KIT))
    import buyers  # the kit file, read-only
    assert len(buyers.TACTICS) == len(TACTIC_TAGS), "kit tactics changed; update TACTIC_TAGS"
    store = [s for s in load_store() if s["stock"] > 0]
    gone = [s for s in load_store() if s["stock"] == 0]
    r = rng("kit")
    out = []

    def basket():
        items = r.sample(store, r.choice([1, 1, 1, 2]))
        lines = [(s, r.choice([1, 1, 2, 3])) for s in items]
        listed = sum(s["price"] * q for s, q in lines)
        return " and ".join(f"{q} x {s['name']} ({s['sku']})" for s, q in lines), listed, lines

    for k, (tactic, tags) in enumerate(zip(buyers.TACTICS, TACTIC_TAGS)):
        for v in range(n_per_tactic):
            desc, listed, lines = basket()
            fake = int(listed * r.uniform(0.3, 0.5) / 10) * 10
            bid = int(listed * r.uniform(0.35, 0.6) / 10) * 10
            body = tactic.format(fake=fake)
            if v % 2 == 0:
                text, extra = f"I need {desc}. {body} My offer: ₹{bid:,}.", []
            else:
                text, extra = f"{body} My offer: ₹{bid:,}.", []
                trick = v % 6
                if trick == 1 and gone:
                    g = r.choice(gone)
                    text += f" Add one {g['name']} ({g['sku']}) too, at full price."
                    extra = ["scope_change"]
                elif trick == 3:
                    s, _ = lines[0]
                    text += f" Actually make it {s['stock'] + 5} of {s['sku']}."
                    extra = ["scope_change"]
                elif trick == 5:
                    c = r.choice(store)
                    text += f" And throw in a {c['name']} ({c['sku']}) for ₹1."
                    extra = ["scope_change"]
            out.append({"id": f"kit-tactic{k}-{v}", "text": text, "tags": clean_tags(tags + extra), "source": "kit"})
    for k, (tpl, tags) in enumerate(BOT_LINES):
        for v in range(3 if "{t}" in tpl else 1):
            _, listed, _ = basket()
            text = tpl.format(t=f"₹{int(listed * r.uniform(0.5, 0.95) / 10) * 10:,}")
            out.append({"id": f"kit-bot{k}-{v}", "text": text, "tags": clean_tags(tags), "source": "kit"})
    for v in range(12):
        desc, listed, lines = basket()
        bid = int(listed * r.uniform(0.6, 0.7) / 10) * 10
        if v % 2:
            out.append({"id": f"kit-open-hb-{v}", "source": "kit", "tags": ["bundle_request"],
                        "text": f"{desc}. I'll pay ₹{bid:,}. I'm buying several, so I expect a proper bundle discount."})
        else:
            out.append({"id": f"kit-open-coop-{v}", "source": "kit", "tags": ["tone_friendly"],
                        "text": f"Hi, I'd like {desc}. Could you do ₹{bid:,}?"})
    return out


# ---------------------------------------------------------------- Codex caches


def codex_lines(which):
    out = []
    for f in sorted((DATA / "codex_cache" / which).glob(f"{which}-*.json")):
        rec = json.loads(f.read_text(encoding="utf-8"))
        if not rec.get("ok"):
            continue
        for i, line in enumerate(rec["response"]["lines"]):
            text = (line.get("text") or "").strip()
            if text:
                out.append({"id": f"{rec['job']['id']}-{i}", "text": text, "tags": clean_tags(line.get("tags")),
                            "source": "codex" if which == "train" else "heldout", "job": rec["job"]["kind"]})
    return out


CORRECTIONS = DATA / "heldout_corrections.json"


def apply_corrections(heldout):
    """Apply the reviewed held-out label corrections (data/heldout_corrections.json; tags null = drop line)."""
    fixes = json.loads(CORRECTIONS.read_text(encoding="utf-8")) if CORRECTIONS.exists() else {}
    out, changed, removed = [], 0, 0
    for row in heldout:
        fx = fixes.get(text_key(row["text"]))
        if fx is None:
            out.append(row)
        elif fx["tags"] is None:
            removed += 1
        else:
            out.append(dict(row, tags=clean_tags(fx["tags"]), corrected=True))
            changed += 1
    return out, changed, removed


def group_of(row):
    """Generation group: a Codex job, a kit template, a CaSiNo dialogue (the row id minus its last part)."""
    return row["id"].rsplit("-", 1)[0]


def grouped_split(pool, frac):
    """Validation = whole generation groups, stratified by tag, so threshold calibration sees unseen styles
    (as the held-out set and real buyers will) while every tag still gets about `frac` of its positives.
    A random line split leaks each Codex job's style into validation and inflates confidence.

    Rarest tag first: add the group whose count of that tag best fits the remaining share (small overshoot,
    so training keeps most of each tag) until the tag has its share; then top up with
    groups that carry no tag until validation holds about `frac` of all lines.
    """
    groups = {}
    for row in pool:
        groups.setdefault(group_of(row), []).append(row)
    keys = sorted(groups)
    rng("split").shuffle(keys)
    total = Counter(t for row in pool for t in row["tags"])
    have, chosen = Counter(), set()
    def pos(k, tag):
        return sum(tag in row["tags"] for row in groups[k])

    for tag in sorted(TAGS, key=lambda t: total[t]):
        while have[tag] < frac * total[tag]:
            need = frac * total[tag] - have[tag]
            cands = [k for k in keys if k not in chosen and pos(k, tag)]
            if not cands:
                break
            k = min(cands, key=lambda c: abs(pos(c, tag) - need))  # best fit; ties keep shuffled order
            chosen.add(k)
            have.update(t for row in groups[k] for t in row["tags"])
    n = sum(len(groups[k]) for k in chosen)
    for k in keys:
        if n >= frac * len(pool):
            break
        if k not in chosen and not any(row["tags"] for row in groups[k]):
            chosen.add(k)
            n += len(groups[k])
    valid = [row for k in keys if k in chosen for row in groups[k]]
    train = [row for k in keys if k not in chosen for row in groups[k]]
    return valid, train


def dedup(rows, banned=frozenset()):
    seen, out, dropped = set(banned), [], 0
    for row in rows:
        k = text_key(row["text"])
        if k in seen:
            dropped += 1
            continue
        seen.add(k)
        out.append(row)
    return out, dropped


def tag_counts(rows):
    c = Counter(t for r in rows for t in r["tags"])
    return {t: c.get(t, 0) for t in TAGS}


def write_readme(counts, splits, leak_dropped, casino_unlab, notes, corrections=(0, 0)):
    lines = ["# S3 tag dataset", "", "Built by `training/build_dataset.py`. Tags: `training/TAGS.md`.", "",
             "## Sources, counts and licences", "",
             "| Source | Lines (after dedup) | Origin | Licence |", "|---|---|---|---|"]
    for src in ("casino", "kit", "codex", "heldout", "handwritten", "craigslist"):
        origin, lic = LICENCES[src]
        lines.append(f"| {src} | {counts.get(src, 0)} | {origin} | {lic} |")
    lines += ["", f"Unlabelled CaSiNo utterances (distillation corpus only): {casino_unlab}.",
              f"Training lines dropped because their text matches a held-out line: {leak_dropped}.",
              f"Held-out labels reviewed line by line against TAGS.md: {corrections[0]} corrected, "
              f"{corrections[1]} removed (data/heldout_corrections.json records each change and why).", "",
              "## Splits", "", "| Split | Lines | Use |", "|---|---|---|",
              f"| train.jsonl | {splits['train']} | SetFit training |",
              f"| valid.jsonl | {splits['valid']} | per-tag threshold calibration: whole generation groups unseen in train |",
              f"| heldout.jsonl | {splits['heldout']} | final evaluation only, different prompt template |",
              "| heldout_handwritten.jsonl | 60 | second, independent held-out set (robustness check) |",
              f"| unlabelled.jsonl | {splits['unlabelled']} | extra text for distilling the linear fallback |",
              "", "## Positive lines per tag", "", "| Tag | train | valid | heldout |", "|---|---|---|---|"]
    for t in TAGS:
        lines.append(f"| `{t}` | {splits['tags_train'][t]} | {splits['tags_valid'][t]} | {splits['tags_heldout'][t]} |")
    lines += ["", "## Mapping notes", ""] + [f"- {n}" for n in notes] + [""]
    (DATA / "README.md").write_text("\n".join(lines), encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--with-craigslist", type=Path, default=None)
    ap.add_argument("--casino-cap", type=int, default=800, help="max labelled CaSiNo lines in the training pool")
    ap.add_argument("--valid-frac", type=float, default=0.15)
    a = ap.parse_args(argv)

    heldout, _ = dedup(codex_lines("heldout"))
    handwritten = read_jsonl(DATA / "heldout_handwritten.jsonl")  # second held-out set, written by hand
    banned = {text_key(r["text"]) for r in heldout + handwritten}
    heldout, n_corrected, n_removed = apply_corrections(heldout)

    casino_lab, casino_unlab = casino_lines(fetch_casino())
    r = rng("casino-sample")
    tagged = [x for x in casino_lab if x["tags"]]
    plain = [x for x in casino_lab if not x["tags"]]
    r.shuffle(tagged)
    r.shuffle(plain)
    casino = tagged[: a.casino_cap * 2 // 3] + plain[: a.casino_cap - min(len(tagged), a.casino_cap * 2 // 3)]

    pool = codex_lines("train") + kit_lines() + casino
    if a.with_craigslist:
        pool += [dict(x, source="craigslist") for x in read_jsonl(a.with_craigslist)]
    n_before = len(pool)
    pool, _ = dedup(pool)
    n_dups = n_before - len(pool)
    pool, leak_dropped = dedup(pool, banned)
    counts = Counter(x["source"] for x in pool)
    counts["heldout"] = len(heldout)
    counts["handwritten"] = len(handwritten)

    valid, train = grouped_split(pool, a.valid_frac)
    unlab, _ = dedup(casino_unlab, banned | {text_key(x["text"]) for x in pool})

    write_jsonl(DATA / "train.jsonl", train)
    write_jsonl(DATA / "valid.jsonl", valid)
    write_jsonl(DATA / "heldout.jsonl", heldout)
    write_jsonl(DATA / "unlabelled.jsonl", unlab)
    splits = {"train": len(train), "valid": len(valid), "heldout": len(heldout), "unlabelled": len(unlab),
              "tags_train": tag_counts(train), "tags_valid": tag_counts(valid), "tags_heldout": tag_counts(heldout)}
    notes = [
        "CaSiNo strategies: small-talk, showing-empathy -> `tone_friendly`; "
        "no tag for the others; lines carrying self-need or other-need are left out (too ambiguous for `claim_hardship`) and used as unlabelled text. Deal-action rows (Submit-Deal etc.) are skipped. "
        f"Capped at {a.casino_cap} lines (about two thirds tagged) so the campsite domain does not dominate.",
        "Kit tactics: the ten buyers.TACTICS strings labelled per TAGS.md (see TACTIC_TAGS), rendered with real "
        "store items, half as openings and half as counters, a third of the counters with an item trick "
        "(-> `scope_change`). Plus every fixed phrase of the three kit bots.",
        "Codex lines keep the generator's own labels, filtered to known tags.",
        "Dedup and leakage guard: case/whitespace-insensitive text hash; held-out texts are banned from every "
        "other split.",
    ]
    write_readme(counts, splits, leak_dropped, len(unlab), notes, (n_corrected, n_removed))
    print(json.dumps({"sources": dict(counts), **{k: v for k, v in splits.items() if not k.startswith("tags")},
                      "dropped_duplicates": n_dups, "dropped_heldout_collisions": leak_dropped,
                      "heldout_corrected": n_corrected, "heldout_removed": n_removed}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
