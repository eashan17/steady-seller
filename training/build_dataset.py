"""Build the tag dataset from its sources and write per-source counts and licences (S3 / T02).

    python -X utf8 training/build_dataset.py [--with-craigslist PATH] [--casino-cap 800]

Sources (see training/data/README.md, which this script rewrites):
  casino     CaSiNo (Chawla et al., NAACL 2021), CC-BY-4.0. Strategy annotations mapped onto our tags.
             Downloaded once through the Hugging Face datasets-server rows API into data/raw/.
  kit        the kit's ten manipulator tactics and item tricks (buyers.py:142-191) and the other bots' lines,
             rendered with real store items and labelled by hand here.
  codex      synthetic lines from training/codex_gen.py --set train (labels from the generator).
  heldout    training/codex_gen.py --set heldout: a different prompt template, labels reviewed by hand
             (data/heldout_corrections.json). Written to heldout.jsonl only;
             any training line whose normalised text collides with a held-out line is dropped.
  craigslist CraigslistBargain is EXCLUDED by default: no licence is stated anywhere (HF card: "unknown").
             --with-craigslist takes a local JSONL of {"text", "tags"} if the licence question is resolved.

Outputs in training/data/: train.jsonl, valid.jsonl (15% of the training pool, for threshold calibration),
heldout.jsonl, unlabelled.jsonl (extra buyer-like text for distillation), README.md.
"""
import argparse
import json
import sys
import time
import urllib.request
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import DATA, KIT, TAGS, clean_tags, load_store, read_jsonl, rng, text_key, write_jsonl  # noqa: E402

RAW = DATA / "raw"
CASINO_RAW = RAW / "casino_rows.jsonl"
CASINO_URL = ("https://datasets-server.huggingface.co/rows?dataset=kchawla123/casino"
              "&config=default&split=train&offset={offset}&length=100")
CASINO_MAP = {"small-talk": ["tone_friendly"], "showing-empathy": ["tone_friendly"]}
# self-need / other-need mix real hardship ("my friend's life depends on it") with plain preference ("I'd like
# firewood for the campfire"), so they would be noisy for `claim_hardship` either way: such lines are kept out
# of the labelled pool and used only as unlabelled distillation text.
CASINO_AMBIGUOUS = {"self-need", "other-need"}
CASINO_SKIP = {"Submit-Deal", "Accept-Deal", "Reject-Deal", "Walk-Away"}

LICENCES = {
    "casino": ("CaSiNo, Chawla et al. 2021 (github.com/kushalchawla/CaSiNo; HF kchawla123/casino)",
               "CC-BY-4.0 (GitHub repo licence badge; HF cardData.license = cc-by-4.0). Attribution given here."),
    "kit": ("AgentX PS2 kit, ps2-selling-to-machines/buyers.py:89-197", "Hackathon kit, used as provided"),
    "codex": ("Synthetic, generated by us via Codex CLI (`codex exec`, ChatGPT Go plan), training/codex_gen.py",
              "Our own generated data (OpenAI terms: output belongs to the user)"),
    "heldout": ("Synthetic, generated by us via Codex CLI with a different prompt template",
                "Our own generated data; evaluation only, never trained on"),
    "handwritten": ("Written by hand (Claude, offline) in wording independent of TAGS.md examples: "
                    "data/heldout_handwritten.jsonl", "Our own data; second held-out set, evaluation only"),
    "craigslist": ("CraigslistBargain, He et al. 2018 (HF stanfordnlp/craigslist_bargains)",
                   "NOT USED: no licence stated (HF card 'unknown', project page silent)"),
}


# ---------------------------------------------------------------- CaSiNo


def fetch_casino():
    if CASINO_RAW.exists():
        return read_jsonl(CASINO_RAW)
    rows, offset, total = [], 0, None
    while total is None or offset < total:
        req = urllib.request.Request(CASINO_URL.format(offset=offset), headers={"User-Agent": "dataset-builder"})
        with urllib.request.urlopen(req, timeout=60) as r:
            page = json.loads(r.read().decode("utf-8"))
        total = page["num_rows_total"]
        rows.extend(x["row"] for x in page["rows"])
        offset += 100
        time.sleep(0.5)
    write_jsonl(CASINO_RAW, rows)
    return rows


def casino_lines(rows):
    labelled, unlabelled = [], []
    for d, row in enumerate(rows):
        anns = row.get("annotations") or []
        if anns:
            for u, (text, labels) in enumerate(anns):
                labs = {lab.strip() for lab in labels.split(",")}
                if labs & CASINO_AMBIGUOUS or text.strip() in CASINO_SKIP:
                    if text.strip() not in CASINO_SKIP:
                        unlabelled.append({"id": f"casino-a-{d}-{u}", "text": text, "source": "casino-unlabelled"})
                    continue
                tags = sorted({t for lab in labs for t in CASINO_MAP.get(lab, [])})
                labelled.append({"id": f"casino-{d}-{u}", "text": text, "tags": clean_tags(tags), "source": "casino",
                                 "orig": labels})
        else:
            for u, turn in enumerate(row.get("chat_logs") or []):
                text = (turn.get("text") or "").strip()
                if text and text not in CASINO_SKIP:
                    unlabelled.append({"id": f"casino-u-{d}-{u}", "text": text, "source": "casino-unlabelled"})
    return labelled, unlabelled


